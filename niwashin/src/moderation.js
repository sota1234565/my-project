// 名前や観察記録に、下ネタ・悪口が入らないようにするための簡易フィルター。
//
// 【正直な注意】言い換えや伏せ字ですり抜けられるため、完璧ではない。
// ここは「うっかり・軽い悪意」を止める入口で、最後の砦は管理画面からのリセット。
//
// 同じパターンを database.rules.json の .validate（サーバー側）にも入れてある。
// ここを変えたら、あちらも必ず同じ内容にそろえること（ずれると片方だけ通ってしまう）。
//
// 短いひらがな（ばか・かす・はげ 等）は普通の名前にも含まれやすく誤爆するので、
// カタカナ・漢字の形だけ登録している。特に悪質なもの（死ね・殺す）はひらがなも含む。
export const NG_SOURCE =
  '死ね|しね|殺す|ころす|バカ|馬鹿|アホ|カス|クズ|キモ|ブス|デブ|ハゲ|ウザ|うざ|' +
  'キチガイ|きちがい|ガイジ|池沼|糞|クソ|くそ|うんこ|ウンコ|' +
  'ちんこ|チンコ|ちんちん|チンチン|まんこ|マンコ|おっぱい|オッパイ|' +
  'セックス|せっくす|エロ|えろ|レイプ|売春|風俗|変態|へんたい|' +
  'fuck|shit|bitch|asshole|dick|pussy|cock|porn|rape|nigger|faggot|cunt|whore|slut';

const NG_RE = new RegExp(NG_SOURCE, 'i');

// 使えない言葉が含まれていれば true
export function hasNgWord(text) {
  return NG_RE.test(String(text || ''));
}
